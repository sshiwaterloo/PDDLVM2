#!/usr/bin/env python
"""Generate static API docs from docstrings using stdlib pydoc.

Zero-dependency documentation generator for offline environments (no
sphinx/pdoc needed).  Produces per-module HTML pages plus a small index
under ``docs/api/``.

Usage (from the repo root):
    python tools/build_docs.py

Sphinx remains the recommended pipeline for a full docs site; this tool
exists so API docs can be built and verified without network access.
"""

import os
import pydoc
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "api")

MODULES = [
    "pddlvm",
    "pddlvm.experiment",
    "pddlvm.plotting",
    "pddlvm.numerics",
    "pddlvm.numerics.chebyshev",
    "pddlvm.numerics.fem",
    "pddlvm.numerics.fd",
    "pddlvm.numerics.mms",
    "pddlvm.probabilistic",
    "pddlvm.probabilistic.distributions",
    "pddlvm.probabilistic.elbo",
    "pddlvm.probabilistic.trainer",
    "pddlvm.probabilistic.checkpointing",
    "pddlvm.VEModel",
    "pddlvm.NeuralNet",
    "pddlvm.poisson1DPDEState",
    "pddlvm.poisson1DSolver",
]


def main():
    os.makedirs(OUT, exist_ok=True)
    sys.path.insert(0, ROOT)
    pages = []
    for module in MODULES:
        target = os.path.join(OUT, module.replace(".", "_") + ".html")
        # pydoc -w writes "<module>.html" into the CWD; render in OUT
        subprocess.run(
            [sys.executable, "-m", "pydoc", "-w", module],
            cwd=OUT, check=True)
        written = os.path.join(OUT, module + ".html")
        if written != target:
            os.replace(written, target)
        pages.append((module, os.path.basename(target)))

    index = os.path.join(OUT, "index.html")
    with open(index, "w") as fh:
        fh.write("<!DOCTYPE html><html><head><meta charset='utf-8'>"
                 "<title>pddlvm API</title></head><body>\n")
        fh.write("<h1>pddlvm API documentation</h1>\n<ul>\n")
        for module, page in pages:
            fh.write(f"  <li><a href='{page}'>{module}</a></li>\n")
        fh.write("</ul>\n<p>Generated by <code>tools/build_docs.py</code> "
                 "(stdlib pydoc).</p>\n</body></html>\n")
    print(f"docs written to {OUT} ({len(pages)} modules + index)")


if __name__ == "__main__":
    main()
